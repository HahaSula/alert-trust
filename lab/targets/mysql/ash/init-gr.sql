-- MySQL 8.4 Group Replication 節點。init 期間不寫 binlog，最後清掉 GTID，三台從同一個空狀態開始。
SET SQL_LOG_BIN = 0;
CREATE USER 'exporter'@'%' IDENTIFIED BY 'exporterpw' WITH MAX_USER_CONNECTIONS 4;
GRANT PROCESS, REPLICATION CLIENT, SELECT ON *.* TO 'exporter'@'%';
CREATE USER 'rpl'@'%' IDENTIFIED BY 'rplpw';
GRANT REPLICATION SLAVE, CONNECTION_ADMIN, BACKUP_ADMIN, GROUP_REPLICATION_STREAM ON *.* TO 'rpl'@'%';
SET SQL_LOG_BIN = 1;
RESET BINARY LOGS AND GTIDS;
